export function applyLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.title = t.meta.title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t.meta.description);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const value = key.split('.').reduce((obj, k) => obj?.[k], t);
    if (value === undefined) return;

    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = value;
    } else if (el.tagName === 'OPTION') {
      el.textContent = value;
    } else {
      el.innerHTML = String(value).replace(/\n/g, '<br />');
    }
  });

  const langBtn = document.getElementById('langToggle');
  if (langBtn) langBtn.textContent = t.nav.langSwitch;

  const scrollLink = document.querySelector('.hero__scroll');
  if (scrollLink) scrollLink.setAttribute('aria-label', t.hero.scroll);

  localStorage.setItem('layali-lang', lang);
}
